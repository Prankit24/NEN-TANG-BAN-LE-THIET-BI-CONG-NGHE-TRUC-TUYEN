-- 1. BẢNG PHIẾU NHẬP HÀNG
CREATE TABLE IF NOT EXISTS public."PhieuNhapHang" (
    "MaPhieuNhap" integer GENERATED BY DEFAULT AS IDENTITY,
    "MaChungTu" character varying(50) NOT NULL,
    "NhaCungCap" character varying(200) NOT NULL,
    "LyDoNhap" character varying(255) NOT NULL,
    "DienGiai" character varying(500) NULL,
    "TrangThai" character varying(50) NOT NULL DEFAULT 'Chờ duyệt',
    "MaNguoiTao" integer NOT NULL,
    "NgayTao" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "MaNguoiDuyet" integer NULL,
    "NgayDuyet" timestamp without time zone NULL,
    "LyDoTuChoi" character varying(500) NULL,
    "GhiChu" character varying(500) NULL,
    "TongTienDuKien" numeric(18,2) NOT NULL DEFAULT 0,
    "NgayNhapKho" timestamp without time zone NULL,
    "MaNguoiNhapKho" integer NULL,
    CONSTRAINT "PK_PhieuNhapHang" PRIMARY KEY ("MaPhieuNhap"),
    CONSTRAINT "CK_PhieuNhapHang_TrangThai" CHECK ("TrangThai" IN ('Chờ duyệt', 'Đã duyệt', 'Từ chối', 'Đã nhập kho', 'Đã hủy')),
    CONSTRAINT "CK_PhieuNhapHang_TongTienDuKien" CHECK ("TongTienDuKien" >= 0),
    CONSTRAINT "FK_PhieuNhapHang_NguoiDung_MaNguoiTao" FOREIGN KEY ("MaNguoiTao") REFERENCES public."nguoidung" ("manguoidung") ON DELETE RESTRICT,
    CONSTRAINT "FK_PhieuNhapHang_NguoiDung_MaNguoiDuyet" FOREIGN KEY ("MaNguoiDuyet") REFERENCES public."nguoidung" ("manguoidung") ON DELETE RESTRICT,
    CONSTRAINT "FK_PhieuNhapHang_NguoiDung_MaNguoiNhapKho" FOREIGN KEY ("MaNguoiNhapKho") REFERENCES public."nguoidung" ("manguoidung") ON DELETE RESTRICT
);

-- Chỉ mục cho bảng PhieuNhapHang
CREATE UNIQUE INDEX IF NOT EXISTS "IX_PhieuNhapHang_MaChungTu" ON public."PhieuNhapHang" ("MaChungTu");
CREATE INDEX IF NOT EXISTS "IX_PhieuNhapHang_MaNguoiTao" ON public."PhieuNhapHang" ("MaNguoiTao");
CREATE INDEX IF NOT EXISTS "IX_PhieuNhapHang_TrangThai" ON public."PhieuNhapHang" ("TrangThai");

-- 2. BẢNG CHI TIẾT PHIẾU NHẬP HÀNG
CREATE TABLE IF NOT EXISTS public."ChiTietPhieuNhapHang" (
    "MaChiTietPhieuNhap" integer GENERATED BY DEFAULT AS IDENTITY,
    "MaPhieuNhap" integer NOT NULL,
    "MaBienThe" integer NOT NULL,
    "SoLuongNhap" integer NOT NULL DEFAULT 1,
    "DonGiaNhapDuKien" numeric(18,2) NOT NULL DEFAULT 0,
    "GhiChu" character varying(255) NULL,
    CONSTRAINT "PK_ChiTietPhieuNhapHang" PRIMARY KEY ("MaChiTietPhieuNhap"),
    CONSTRAINT "CK_ChiTietPhieuNhapHang_SoLuongNhap" CHECK ("SoLuongNhap" > 0),
    CONSTRAINT "CK_ChiTietPhieuNhapHang_DonGiaNhapDuKien" CHECK ("DonGiaNhapDuKien" >= 0),
    CONSTRAINT "FK_ChiTietPhieuNhapHang_PhieuNhapHang" FOREIGN KEY ("MaPhieuNhap") REFERENCES public."PhieuNhapHang" ("MaPhieuNhap") ON DELETE CASCADE,
    CONSTRAINT "FK_ChiTietPhieuNhapHang_BienTheSanPham" FOREIGN KEY ("MaBienThe") REFERENCES public."bienthesanpham" ("mabienthe") ON DELETE RESTRICT
);

-- Chỉ mục cho bảng ChiTietPhieuNhapHang
CREATE INDEX IF NOT EXISTS "IX_ChiTietPhieuNhapHang_MaPhieuNhap" ON public."ChiTietPhieuNhapHang" ("MaPhieuNhap");
CREATE INDEX IF NOT EXISTS "IX_ChiTietPhieuNhapHang_MaBienThe" ON public."ChiTietPhieuNhapHang" ("MaBienThe");
